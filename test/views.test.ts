import fc from "fast-check";
import type pg from "pg";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import { apply, Database, logins, refusal } from "./database.ts";

const schema = `
  create table orders (
    id        integer generated by default as identity primary key,
    customer  text not null,
    status    text not null default 'paid',
    refunded  numeric(10, 2) not null default 0,
    region    text not null default 'north'
  );
  insert into orders (customer, region) select 'customer ' || n, case when n <= 30 then 'north' else 'south' end from generate_series(1, 40) as n;
  select keyturn.protect('orders');
  grant select on orders to keyturn_agent, keyturn_approver;

  -- The agent sees the north's orders only.
  alter table orders enable row level security;
  create policy north on orders for select to keyturn_agent using (region = 'north');
  create policy all_rows on orders for select to keyturn_approver using (true);

  -- Two tables of the same shape: one written through Keyturn, one written directly.
  create table through (id integer primary key, a integer, b text, c boolean not null default false);
  create table direct (like through including all);
  select keyturn.protect('through');
  grant select on through to keyturn_agent, keyturn_approver;
`;

let database: Database;
let owner: pg.Client;
let agent: pg.Client;
let alice: pg.Client;

beforeAll(async () => {
  database = await Database.create(schema);
  [owner, agent, alice] = await Promise.all([
    database.as(logins.owner),
    database.as(logins.agent),
    database.as(logins.alice),
  ]);
});

afterAll(async () => {
  await database.close();
});

type Proposed = { proposal_id: string; content_hash: string; changes: string };
/** Runs statements as the agent in one transaction and gives back the proposal they made, if any. */
async function proposing(
  client: pg.Client,
  ...statements: string[]
): Promise<Proposed | undefined> {
  await client.query("begin");
  try {
    for (const statement of statements) await client.query(statement);
    const proposed = (await client.query<Proposed>("select * from keyturn.proposed()")).rows[0];
    await client.query("commit");
    return proposed;
  } catch (error) {
    await client.query("rollback");
    throw error;
  }
}
const approve = (proposed: Proposed) =>
  alice.query("select keyturn.approve($1, $2)", [proposed.proposal_id, proposed.content_hash]);
const order = async (id: number) =>
  (
    await owner.query(
      "select id, customer, status, refunded::text, region from orders where id = $1",
      [id],
    )
  ).rows[0];
const changes = async (proposed: Proposed) =>
  (
    await alice.query(
      "select operation, key, before, after, columns from keyturn.changes where proposal_id = $1 order by seq",
      [proposed.proposal_id],
    )
  ).rows;

describe("ordinary SQL against a view", () => {
  test("an update writes nothing, says so, and becomes a proposal", async () => {
    const result = await agent.query(
      "update proposal.orders set status = 'refunded', refunded = 400 where id = 1",
    );

    // No rows changed: that is what happened.
    expect(result.rowCount).toBe(0);
    expect(await order(1)).toMatchObject({ status: "paid", refunded: "0.00" });
    const proposal = (
      await agent.query(
        "select id, status, note from keyturn.proposals order by proposed_at desc limit 1",
      )
    ).rows[0];
    expect(proposal.status).toBe("pending");
    const recorded = (
      await alice.query(
        "select operation, key, columns, before, after from keyturn.changes where proposal_id = $1",
        [proposal.id],
      )
    ).rows;
    expect(recorded).toEqual([
      {
        operation: "update",
        key: { id: 1 },
        columns: ["refunded", "status"],
        before: { id: 1, customer: "customer 1", status: "paid", refunded: 0, region: "north" },
        after: {
          id: 1,
          customer: "customer 1",
          status: "refunded",
          refunded: 400,
          region: "north",
        },
      },
    ]);
  });

  test("the statements of one transaction are one proposal, approved and applied together", async () => {
    const proposed = (await proposing(
      agent,
      "select keyturn.note('Merging two customers.')",
      "update proposal.orders set customer = 'customer 2' where id = 3",
      "delete from proposal.orders where id = 4",
      "insert into proposal.orders (customer, status) values ('walk-in', 'open')",
    )) as Proposed;

    expect(proposed.changes).toBe("3");
    expect((await changes(proposed)).map((change) => change.operation)).toEqual([
      "update",
      "delete",
      "insert",
    ]);
    expect(
      (
        await alice.query("select note from keyturn.proposals where id = $1", [
          proposed.proposal_id,
        ])
      ).rows[0].note,
    ).toBe("Merging two customers.");

    await approve(proposed);
    expect(await apply(agent, proposed.proposal_id)).toEqual({ status: "applied", changes: 3 });

    expect(await order(3)).toMatchObject({ customer: "customer 2" });
    expect(await order(4)).toBeUndefined();
    // The inserted row took its id and its region from the table's own defaults, when it was really inserted.
    const inserted = (
      await owner.query("select id, status, region from orders where customer = 'walk-in'")
    ).rows;
    expect(inserted).toEqual([{ id: 41, status: "open", region: "north" }]);
  });

  test("a statement with no condition proposes every row it can reach, and no row it cannot", async () => {
    const proposed = (await proposing(
      agent,
      "update proposal.orders set status = 'audited'",
    )) as Proposed;
    const recorded = await changes(proposed);

    // The north's rows, less the one deleted above, plus the one inserted. None of the south's ten.
    expect(recorded.every((change) => change.before.region === "north")).toBe(true);
    expect(recorded.length).toBe(
      (await owner.query("select count(*)::int as n from orders where region = 'north'")).rows[0].n,
    );
    expect(
      (await owner.query("select count(*)::int as n from orders where status = 'audited'")).rows[0]
        .n,
    ).toBe(0);
    await alice.query("select keyturn.reject($1, 'Too broad.')", [proposed.proposal_id]);
  });

  test("a transaction that is rolled back proposes nothing", async () => {
    const before = (await owner.query("select count(*)::int as n from keyturn.proposals")).rows[0]
      .n;

    await agent.query("begin; update proposal.orders set status = 'x' where id = 5; rollback");

    expect((await owner.query("select count(*)::int as n from keyturn.proposals")).rows[0].n).toBe(
      before,
    );
  });

  test("a statement that changes nothing proposes nothing", async () => {
    expect(
      await proposing(
        agent,
        "update proposal.orders set status = status where id = 5",
        "update proposal.orders set status = 'x' where id = 99999",
      ),
    ).toBeUndefined();
  });

  test("what it cannot express is refused, with the reason", async () => {
    const message = async (...statements: string[]) =>
      (await refusal(proposing(agent, ...statements)))?.message;

    expect(await message("update proposal.orders set id = 9000 where id = 5")).toContain(
      "primary key is not changed by an update",
    );
    expect(
      await message(
        "update proposal.orders set status = 'a' where id = 5",
        "update proposal.orders set status = 'b' where id = 5",
      ),
    ).toContain("already has a change in this proposal");
    expect(await message("truncate proposal.orders")).toMatch(/not a table|cannot truncate/);
    expect(
      await message(
        "insert into proposal.orders (id, customer) values (1, 'x') on conflict (id) do nothing",
      ),
    ).toContain("ON CONFLICT");
    expect(await order(5)).toMatchObject({ status: "paid" });
  });

  test("a row hidden by row-level security is not reached through the view either", async () => {
    // Order 35 is in the south.
    expect(
      await proposing(
        agent,
        "update proposal.orders set status = 'x' where id = 35",
        "delete from proposal.orders where id = 36",
      ),
    ).toBeUndefined();
    expect(
      (await agent.query("select count(*)::int as n from proposal.orders where region = 'south'"))
        .rows[0].n,
    ).toBe(0);
  });
});

describe("a view is not a way in", () => {
  test("the table itself still refuses the agent", async () => {
    expect((await refusal(agent.query("update orders set status = 'x' where id = 6")))?.code).toBe(
      "42501",
    );
  });

  test("a view whose trigger is gone refuses the write and does not pass it on", async () => {
    await owner.query("drop trigger capture on proposal.orders");
    try {
      const attempt = await refusal(
        agent.query("update proposal.orders set status = 'written straight through' where id = 6"),
      );

      expect(attempt).not.toBeNull();
      expect(await order(6)).toMatchObject({ status: "paid" });
    } finally {
      await owner.query("select keyturn.protect('orders')");
    }
  });

  test("only an agent can write to a view, and a view made by the agent is not one of Keyturn's", async () => {
    expect(
      (await refusal(alice.query("update proposal.orders set status = 'x' where id = 6")))?.code,
    ).toBe("42501");
    expect((await refusal(agent.query("create view proposal.mine as select 1")))?.code).toBe(
      "42501",
    );
    // A view of its own, elsewhere, with Keyturn's trigger on it, to feed in rows of its own making.
    await agent.query(
      "create temp view forged as select 6 as id, 'x'::text as customer, 'paid'::text as status, 0::numeric as refunded, 'north'::text as region",
    );
    expect(
      (
        await refusal(
          agent.query(
            "create trigger capture instead of update on forged for each row execute function keyturn.capture()",
          ),
        )
      )?.code,
    ).toBe("42501");
  });

  test("a table that has changed shape takes no writes through its view until it is protected again", async () => {
    await owner.query("alter table orders add column note text");
    try {
      expect(
        (await refusal(agent.query("update proposal.orders set status = 'x' where id = 6")))
          ?.message,
      ).toContain("has changed shape since it was protected");
      await owner.query("select keyturn.protect('orders')");
      const proposed = (await proposing(
        agent,
        "update proposal.orders set note = 'now a column' where id = 6",
      )) as Proposed;
      expect((await changes(proposed))[0].columns).toEqual(["note"]);
    } finally {
      await owner.query(
        "select keyturn.drop_view('orders'); alter table orders drop column note; select keyturn.protect('orders')",
      );
    }
  });

  test("changes are added to a proposal only from the transaction that made it", async () => {
    const proposed = (await proposing(
      agent,
      "update proposal.orders set status = 'first' where id = 7",
    )) as Proposed;

    // A later transaction by the same agent starts a proposal of its own.
    const later = (await proposing(
      agent,
      "update proposal.orders set status = 'second' where id = 8",
    )) as Proposed;

    expect(later.proposal_id).not.toBe(proposed.proposal_id);
    expect(await changes(proposed)).toHaveLength(1);
    // So what an approver was shown cannot grow afterwards: the hash they were given still names it.
    expect(
      (await alice.query("select keyturn.hash_of($1) as hash", [proposed.proposal_id])).rows[0]
        .hash,
    ).toBe(proposed.content_hash);
  });
});

describe("through keyturn or directly, the table ends up the same", () => {
  type Step =
    | { kind: "insert"; id: number; a: number | null; b: string | null }
    | { kind: "update"; id: number; a: number | null; c: boolean }
    | { kind: "delete"; id: number };
  const text = fc.constantFrom(
    "",
    "x",
    "it's",
    'say "hi"',
    "æøå",
    "a; drop table through; --",
    null,
  );
  const step: fc.Arbitrary<Step> = fc.oneof(
    fc.record({
      kind: fc.constant("insert" as const),
      id: fc.integer({ min: 1, max: 6 }),
      a: fc.option(fc.integer({ min: -5, max: 5 }), { nil: null }),
      b: text,
    }),
    fc.record({
      kind: fc.constant("update" as const),
      id: fc.integer({ min: 1, max: 6 }),
      a: fc.option(fc.integer({ min: -5, max: 5 }), { nil: null }),
      c: fc.boolean(),
    }),
    fc.record({ kind: fc.constant("delete" as const), id: fc.integer({ min: 1, max: 6 }) }),
  );
  const sql = (table: string, one: Step): { text: string; values: unknown[] } =>
    one.kind === "insert"
      ? {
          text: `insert into ${table} (id, a, b) values ($1, $2, $3)`,
          values: [one.id, one.a, one.b],
        }
      : one.kind === "update"
        ? {
            text: `update ${table} set a = $2, c = $3 where id = $1`,
            values: [one.id, one.a, one.c],
          }
        : { text: `delete from ${table} where id = $1`, values: [one.id] };
  const rows = async (table: string) =>
    (await owner.query(`select * from ${table} order by id`)).rows;

  test("for any run of inserts, updates and deletes", async () => {
    await fc.assert(
      fc.asyncProperty(fc.array(step, { minLength: 1, maxLength: 12 }), async (steps) => {
        await owner.query("truncate direct; delete from through");
        for (const one of steps) {
          // Directly, as the owner. A statement the table refuses (a key already taken) is refused both ways.
          const wrote = (await refusal(owner.query(sql("direct", one)))) === null;

          await agent.query("begin");
          const viaView = await refusal(agent.query(sql("proposal.through", one)));
          const proposed =
            viaView === null
              ? (await agent.query<Proposed>("select * from keyturn.proposed()")).rows[0]
              : undefined;
          await agent.query(viaView === null ? "commit" : "rollback");
          let applied = false;
          if (proposed) {
            await approve(proposed);
            applied = (await apply(agent, proposed.proposal_id)).status === "applied";
          }

          // Proposing alone never changes the table: that was checked by the rows not moving until here.
          expect(await rows("through")).toEqual(await rows("direct"));
          // An insert of a key already there is refused directly, and through Keyturn it is stale at apply.
          if (one.kind === "insert") expect(applied).toBe(wrote);
        }
      }),
      { numRuns: 40 },
    );
  });
});
